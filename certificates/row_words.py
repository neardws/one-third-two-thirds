"""Compact row words for alpha, beta, gamma (letter codes as in the paper, Appendix A).

Run from the repository root:   python3 certificates/row_words.py

Codes: O = {-2..1}, L = {-3..1}, R = {-2..2}, T = {-3..2}, a = {0,1}, b = {-1,0,1}, z = {-3..0}.
The script decodes the listings below and checks that they equal (i) the words stored in
certificates/alpha/certificate.json and in the 'structure' field of the beta/gamma
dominance certificates, and (ii) for beta and gamma, the words regenerated by structure.py.
"""
import json, sys, importlib.util
from pathlib import Path
HERE = Path(__file__).resolve().parent
CODE = {'O': [-2, -1, 0, 1], 'L': [-3, -2, -1, 0, 1], 'R': [-2, -1, 0, 1, 2],
        'T': [-3, -2, -1, 0, 1, 2], 'a': [0, 1], 'b': [-1, 0, 1], 'z': [-3, -2, -1, 0]}
WORDS = {
    'alpha': dict(PRE='abOLRLRLOLRLOLRLOLRLOO', X='LRLOO', MID='LRLOOLORLOO',
                  SUF='LRLOOTOLOTOLOTOTOLOLOz'),
    'beta': dict(PRE='abOLRLRLOLRLOLRLOLRLOLOORLOOLRLROLOLOORLOLOOLROLOLOOO', X='RLOOL',
                 MID='RLOOLRLOOLO',
                 SUF='RLOOLRLOOLROLRLOLOOLROOOTORLOROOORLROLOLROLOTOLOTOLOTOTOLOLOz'),
    'gamma': dict(PRE='abOLRLRLOLRLOLRLOLRLOLOOLOOLOOLOOLOOLOOLOOLOOLOOLOOLO', X='RLOOL',
                  MID='RLOOLRLOOLO',
                  SUF='RLOOLRLOOLOOLOOLOOLOOLOOLOOLOOLOOLOOLOOLROLOTOLOTOLOTOTOLOLOz'),
}
DIRS = {'beta': HERE / 'beta' / 'beta_dominance',
        'gamma': HERE / 'gamma_symleft' / 'symleft_dominance'}


def decode(s): return [CODE[c] for c in s]


def main():
    alpha = json.loads((HERE / 'alpha' / 'certificate.json').read_text())
    for fam, words in WORDS.items():
        if fam == 'alpha':
            stored = alpha
        else:
            stored = json.loads((DIRS[fam] / 'dominance_certificate.json').read_text())['structure']
            sys.path.insert(0, str(DIRS[fam]))
            for mod in ('family', 'structure', 'arithmetic'):
                sys.modules.pop(mod, None)
            spec = importlib.util.spec_from_file_location('structure', DIRS[fam] / 'structure.py')
            st = importlib.util.module_from_spec(spec); spec.loader.exec_module(st)
            regen = st.verify()
            sys.path.pop(0)
        for k, s in words.items():
            assert decode(s) == stored[k], (fam, k, 'stored')
            if fam != 'alpha':
                assert decode(s) == regen[k], (fam, k, 'structure.py')
        if fam != 'alpha':
            assert regen['Y'] == regen['X'] and stored['Y'] == stored['X']
        print(f"{fam}: PRE({len(words['PRE'])}) X={words['X']} MID({len(words['MID'])}) "
              f"SUF({len(words['SUF'])}) match")


if __name__ == '__main__':
    if not __debug__: raise RuntimeError('Run without -O.')
    main()
