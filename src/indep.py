def poset_from_fg(f,g):
    p,q=len(f),len(g); el=[('a',i) for i in range(1,p+1)]+[('b',j) for j in range(1,q+1)]
    R=set()
    for i in range(1,p): R.add((('a',i),('a',i+1)))
    for j in range(1,q): R.add((('b',j),('b',j+1)))
    for i in range(1,p+1):
        if f[i-1]<=q: R.add((('a',i),('b',f[i-1])))
    for j in range(1,q+1):
        if g[j-1]<=p: R.add((('b',j),('a',g[j-1])))
    return el,R
def closure(el,R):
    up={x:set() for x in el}
    for x,y in R: up[x].add(y)
    changed=True
    while changed:
        changed=False
        for x in el:
            new=set().union(*[up[y] for y in up[x]]) if up[x] else set()
            if not new<=up[x]: up[x]|=new; changed=True
    for x in el: assert x not in up[x], "cycle"
    return up
def balance(el,up):
    down={x:{y for y in el if x in up[y]} for x in el}
    idx={x:k for k,x in enumerate(el)}
    bit={x:1<<idx[x] for x in el}; dm={x:sum(bit[y] for y in down[x]) for x in el}
    full=(1<<len(el))-1
    # forward counts over ideals
    F={0:1}; layer=[0]
    for _ in range(len(el)):
        nxt={}
        for I in layer:
            for x in el:
                if not I&bit[x] and (dm[x]&I)==dm[x]:
                    J=I|bit[x]; nxt[J]=nxt.get(J,0)+F[I]
        F.update(nxt); layer=list(nxt)
    e=F[full]
    # backward
    upm={x:sum(bit[y] for y in up[x]) for x in el}
    G={full:1}; layer=[full]
    for _ in range(len(el)):
        nxt={}
        for J in layer:
            for x in el:
                if J&bit[x] and (upm[x]&J)==0 or (J&bit[x] and not (upm[x]&J)):
                    I=J&~bit[x]
                    if I in F: nxt[I]=nxt.get(I,0)+G[J]
        G.update(nxt); layer=list(nxt)
    best=Fr(0);arg=None
    for x,y in itertools.combinations(el,2):
        if y in up[x] or x in up[y]: continue
        k=sum(F[I]*G[I|bit[x]] for I in F if not I&bit[x] and not I&bit[y] and (I|bit[x]) in G)
        m=Fr(min(k,e-k),e)
        if m>best: best=m;arg=(x,y)
    return best,e,arg
